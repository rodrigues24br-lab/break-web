export const LOCALES = ["pt", "es", "en"] as const
export type Locale = (typeof LOCALES)[number]
export const DEFAULT_LOCALE: Locale = "en"
export const LOCALE_COOKIE = "break_locale"

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value.toLowerCase())
}

function fromAcceptLanguage(header: string | null): Locale | null {
  if (!header) return null
  const ranked = header
    .split(",")
    .map((part) => {
      const [tag, q] = part.trim().split(";q=")
      return { lang: tag.slice(0, 2).toLowerCase(), q: q ? Number(q) : 1 }
    })
    .sort((a, b) => b.q - a.q)
  return (ranked.find((entry) => isLocale(entry.lang))?.lang as Locale | undefined) ?? null
}

export function resolveLocale({
  langParam,
  cookieLocale,
  acceptLanguage,
}: {
  langParam?: string | string[]
  cookieLocale?: string
  acceptLanguage: string | null
}): Locale {
  const param = Array.isArray(langParam) ? langParam[0] : langParam
  if (isLocale(param)) return param.toLowerCase() as Locale
  if (isLocale(cookieLocale)) return cookieLocale as Locale
  return fromAcceptLanguage(acceptLanguage) ?? DEFAULT_LOCALE
}

